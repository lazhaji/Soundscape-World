import { describe, expect, it } from 'vitest'
import { mockAudio } from '../helpers/audio'

describe('cinematic audio reuses the application transport', () => {
  it('crossfades weather loops, releases the old loop after the fade, and retains music time', async () => {
    const { engine, sources, gains, factory, advance, context } = mockAudio()
    await engine.startFromGesture()
    advance(4)
    const elapsed = engine.getPlaybackSeconds()
    engine.setWeather('wind')
    expect(factory).toHaveBeenCalledTimes(1)
    expect(sources).toHaveLength(4)
    expect(sources[1]!.stop).toHaveBeenCalledWith(context.currentTime + 0.55)
    expect(sources[1]!.disconnect).not.toHaveBeenCalled()
    expect(gains[9]!.gain.linearRampToValueAtTime).toHaveBeenCalledWith(0, context.currentTime + 0.5)
    expect(gains[10]!.gain.linearRampToValueAtTime).toHaveBeenCalledWith(1, context.currentTime + 0.5)
    expect(sources[0]!.stop).not.toHaveBeenCalled()
    expect(engine.getPlaybackSeconds()).toBe(elapsed)
    engine.setWeather('wind'); expect(sources).toHaveLength(4)
    await engine.dispose()
    expect(sources[1]!.disconnect).toHaveBeenCalledTimes(1)
    expect(sources[3]!.stop).toHaveBeenCalled()
  })
  it('drops interrupted one-shot effects instead of replaying stale sounds on resume', async () => {
    const { engine, sources } = mockAudio()
    engine.playDoorEffect(); expect(sources).toHaveLength(0)
    await engine.startFromGesture()
    engine.playDoorEffect(); expect(sources).toHaveLength(4)
    engine.pauseForBackground()
    expect(sources[3]!.stop).toHaveBeenCalledTimes(1)
    expect(sources[3]!.disconnect).toHaveBeenCalledTimes(1)
    await engine.startFromGesture()
    expect(sources).toHaveLength(4)
    expect(sources[3]!.start).toHaveBeenCalledTimes(1)
  })
  it('keeps sleep melody gain at zero while spatial ambience can change', async () => {
    const { engine, advance } = mockAudio()
    engine.setModeSettings({ mode: 'sleep', mood: 'calm', doNotDisturb: false })
    engine.setAmbientMix({ rain: 0.25, train: 0.4, rolling: 0.5 })
    await engine.startFromGesture(); advance(1)
    expect(engine.getDiagnostics().policyGain).toBe(0)
    expect(engine.getDiagnostics().trainGain).toBeCloseTo(0.4)
    engine.setWorldZone('outside'); engine.clearAmbientMix(); advance(1)
    expect(engine.getDiagnostics().trainGain).toBe(0)
    expect(engine.getDiagnostics().rainGain).toBe(1)
  })
})
